#!/bin/sh
# Regenerate kernels/biot_savart.ptx from kernels/biot_savart.cu.
#
# Uses clang's CUDA device compilation with no CUDA headers or libdevice, so
# neither nvcc nor the CUDA toolkit is needed. Any clang built with the NVPTX
# target works (e.g. Homebrew LLVM). Override with CLANG=/path/to/clang.
#
# The target architecture sets the oldest GPU and, through the PTX ISA
# version it implies, the oldest driver that can load the module (spec 4.5).
set -eu
here=$(cd "$(dirname "$0")" && pwd)
arch=${ARCH:-sm_60}
clang=${CLANG:-}
if [ -z "$clang" ]; then
  for c in /opt/homebrew/opt/llvm/bin/clang /usr/local/opt/llvm/bin/clang clang; do
    if command -v "$c" >/dev/null 2>&1 && "$c" --print-targets 2>/dev/null | grep -q nvptx64; then clang=$c; break; fi
  done
fi
[ -n "$clang" ] || { echo "no clang with the NVPTX target found; set CLANG=" >&2; exit 1; }

"$clang" -x cuda --cuda-device-only --cuda-gpu-arch="$arch" -nocudainc -nocudalib \
  -O3 -ffp-contract=off -fno-fast-math -fcuda-flush-denormals-to-zero=false 2>/dev/null \
  -S -o "$here/biot_savart.ptx.tmp" "$here/biot_savart.cu" ||
"$clang" -x cuda --cuda-device-only --cuda-gpu-arch="$arch" -nocudainc -nocudalib \
  -O3 -ffp-contract=off -fno-fast-math \
  -S -o "$here/biot_savart.ptx.tmp" "$here/biot_savart.cu"

# Refuse output that uses approximate arithmetic: it would break both fp64
# accuracy and the double-single error-free transformations.
if grep -n -E '\.approx|\.ftz|\.full\.' "$here/biot_savart.ptx.tmp"; then
  echo "PTX contains approximate or flush-to-zero instructions" >&2
  rm -f "$here/biot_savart.ptx.tmp"; exit 1
fi
for k in biot_savart_fp64 biot_savart_ds biot_savart_fp32; do
  grep -q "\.entry $k(" "$here/biot_savart.ptx.tmp" || { echo "missing entry $k" >&2; exit 1; }
done
{
  echo "// GENERATED by kernels/build_ptx.sh from biot_savart.cu; do not edit."
  echo "// $("$clang" --version | head -1); target $arch"
  cat "$here/biot_savart.ptx.tmp"
} > "$here/biot_savart.ptx"
rm -f "$here/biot_savart.ptx.tmp"
grep -E '^\.(version|target)' "$here/biot_savart.ptx"
