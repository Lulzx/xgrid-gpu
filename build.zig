const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{ .preferred_optimize_mode = .ReleaseFast });

    const main_mod = b.createModule(.{
        .root_source_file = b.path("src/main.zig"),
        .target = target,
        .optimize = optimize,
    });
    if (target.result.os.tag == .macos) {
        // Metal backend: Objective-C bridge plus the kernel source, embedded
        // and compiled by the OS at startup.
        main_mod.addAnonymousImport("biot_savart.metal", .{ .root_source_file = b.path("kernels/biot_savart.metal") });
        main_mod.addCSourceFile(.{ .file = b.path("src/metal_bridge.m"), .flags = &.{"-fobjc-arc"} });
        main_mod.addIncludePath(b.path("src"));
        // Zig finds the SDK by itself only for the native target; an explicit
        // target such as aarch64-macos.13.0 (used for release binaries, so
        // they run on older macOS) needs its frameworks and libc pointed to.
        if (!target.query.isNative()) {
            if (std.zig.system.darwin.getSdk(b.allocator, b.graph.io, &target.result)) |sdk| {
                main_mod.addSystemFrameworkPath(.{ .cwd_relative = b.pathJoin(&.{ sdk, "System/Library/Frameworks" }) });
                main_mod.addSystemIncludePath(.{ .cwd_relative = b.pathJoin(&.{ sdk, "usr/include" }) });
                main_mod.addLibraryPath(.{ .cwd_relative = b.pathJoin(&.{ sdk, "usr/lib" }) });
            }
        }
        main_mod.linkFramework("Metal", .{});
        main_mod.linkFramework("Foundation", .{});
        main_mod.linkFramework("CoreFoundation", .{});
        main_mod.link_libc = true;
    }
    // CUDA backend: PTX generated by kernels/build_ptx.sh, embedded; the
    // driver is loaded with dlopen at run time, which needs libc.
    main_mod.addAnonymousImport("biot_savart.ptx", .{ .root_source_file = b.path("kernels/biot_savart.ptx") });
    if (target.result.os.tag == .linux) main_mod.link_libc = true;
    const exe = b.addExecutable(.{ .name = "xgrid-gpu", .root_module = main_mod });
    b.installArtifact(exe);

    const netcdf_mod = b.createModule(.{
        .root_source_file = b.path("src/netcdf3.zig"),
        .target = target,
        .optimize = optimize,
    });
    const compare_mod = b.createModule(.{
        .root_source_file = b.path("tests/compare_mgrid.zig"),
        .target = target,
        .optimize = optimize,
    });
    compare_mod.addImport("netcdf3", netcdf_mod);
    const compare = b.addExecutable(.{ .name = "compare_mgrid", .root_module = compare_mod });
    b.installArtifact(compare);

    // Mock CUDA driver for testing the CUDA backend without an NVIDIA GPU:
    // runs the kernels from kernels/biot_savart.cu on the CPU.
    const mock_mod = b.createModule(.{ .target = target, .optimize = .ReleaseFast, .link_libcpp = true });
    mock_mod.addCSourceFile(.{ .file = b.path("tests/cuda_mock/mock_cuda.cpp"), .flags = &.{ "-std=c++17", "-ffp-contract=off", "-fno-fast-math" } });
    mock_mod.addIncludePath(b.path("kernels"));
    const mock = b.addLibrary(.{ .name = "cuda_mock", .linkage = .dynamic, .root_module = mock_mod });
    b.installArtifact(mock);

    const unit_tests = b.addTest(.{ .root_module = main_mod });
    const test_step = b.step("test", "Run unit tests");
    test_step.dependOn(&b.addRunArtifact(unit_tests).step);
}
